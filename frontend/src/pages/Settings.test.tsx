import { render, screen } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { afterEach, expect, it, vi } from 'vitest'
import Settings from './Settings'
afterEach(()=>{localStorage.clear();vi.unstubAllGlobals()})
it('lưu độ phân giải và chế độ gương cho workspace',async()=>{
 vi.stubGlobal('fetch',vi.fn().mockResolvedValue({ok:true,json:async()=>({status:'ok',database:'connected'})}))
 render(<Settings/>)
 await userEvent.selectOptions(screen.getByLabelText('Độ phân giải mong muốn'),'640x480')
 await userEvent.click(screen.getByLabelText('Lật ảnh ngang (chế độ gương)'))
 expect(JSON.parse(localStorage.getItem('rehab.settings')!)).toMatchObject({resolution:'640x480',mirrored:false})
 expect(await screen.findAllByText('Đã kết nối')).toHaveLength(2)
 await userEvent.click(screen.getByLabelText('Ưu tiên giao diện TV'))
 expect(JSON.parse(localStorage.getItem('rehab.settings')!).tvMode).toBe(true)
})
it('lưu lựa chọn Worker CPU và ưu tiên lựa chọn rõ ràng hơn cờ cũ',async()=>{
 vi.stubGlobal('fetch',vi.fn().mockResolvedValue({ok:true,json:async()=>({status:'ok',database:'connected'})}))
 localStorage.setItem('rehab.workerTracking','enabled')
 localStorage.setItem('rehab.settings',JSON.stringify({workerTracking:false}))
 render(<Settings/>)
 const checkbox=screen.getByRole('checkbox',{name:'Sử dụng Worker CPU (thử nghiệm)'})
 expect(checkbox).not.toBeChecked()
 await userEvent.click(checkbox)
 expect(JSON.parse(localStorage.getItem('rehab.settings')!).workerTracking).toBe(true)
})
it('chỉ dùng kích thước profile khi chọn rõ ràng và giữ độ phân giải thủ công',async()=>{
 vi.stubGlobal('fetch',vi.fn().mockResolvedValue({ok:true,json:async()=>({status:'ok',database:'connected'})}))
 localStorage.setItem('rehab.settings',JSON.stringify({trackingProfile:'economy',resolution:'1920x1080'}))
 render(<Settings/>)
 const option=screen.getByRole('checkbox',{name:'Dùng độ phân giải camera theo cấu hình tracking'})
 const manual=screen.getByLabelText('Độ phân giải mong muốn')
 expect(option).not.toBeChecked()
 expect(manual).toHaveValue('1920x1080')
 await userEvent.click(option)
 expect(option).toBeChecked()
 expect(manual).toBeDisabled()
 expect(screen.getByText(/Economy.*640 × 480/)).toBeInTheDocument()
 expect(JSON.parse(localStorage.getItem('rehab.settings')!)).toMatchObject({profileCameraResolution:true,resolution:'1920x1080'})
 await userEvent.click(option)
 expect(manual).toBeEnabled()
 expect(manual).toHaveValue('1920x1080')
 expect(JSON.parse(localStorage.getItem('rehab.settings')!)).toMatchObject({profileCameraResolution:false,resolution:'1920x1080'})
})
it('không bật profile bằng giá trị không hợp lệ trong cấu hình đã lưu',()=>{
 vi.stubGlobal('fetch',vi.fn().mockResolvedValue({ok:true,json:async()=>({status:'ok',database:'connected'})}))
 localStorage.setItem('rehab.settings',JSON.stringify({profileCameraResolution:'true',resolution:'garbage'}))
 render(<Settings/>)
 expect(screen.getByRole('checkbox',{name:'Dùng độ phân giải camera theo cấu hình tracking'})).not.toBeChecked()
 expect(screen.getByLabelText('Độ phân giải mong muốn')).toHaveValue('1280x720')
})
